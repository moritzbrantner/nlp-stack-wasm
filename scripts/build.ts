#!/usr/bin/env bun

// Builds the package from the nlp-stack commit pinned in package.json (`nlpStack`): fetches exactly
// that commit, runs wasm-pack on the text-core and text-index WASM binding crates, and writes for
// each subpath (<name> = text-core-wasm | text-index-wasm)
//   <name>/pkg/moenarch_<crate>.js   wasm-bindgen glue (--target web)
//   <name>/pkg/wasm-bytes.js         the .wasm inlined as a Uint8Array module
//   <name>/index.d.ts                the upstream package's declarations, unchanged
// Needs git, rustup/cargo (the pinned rust-toolchain.toml is installed by rustup) and wasm-pack
// (installed into a user cache with `cargo install --locked` when it is not on PATH).

import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const WASM_PACK_VERSION = "0.14.0";
const PACKAGES = [
  { name: "text-core-wasm", glue: "moenarch_text_core_wasm" },
  { name: "text-index-wasm", glue: "moenarch_text_index_wasm" },
];

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(readFileSync(path.join(packageRoot, "package.json"), "utf8"));
const { repository, commit } = manifest.nlpStack ?? {};
if (typeof repository !== "string" || !/^[0-9a-f]{40}$/.test(commit ?? "")) {
  throw new Error("package.json nlpStack must name a repository and a 40-hex commit");
}

function run(command: string, args: string[], cwd: string) {
  execFileSync(command, args, { cwd, stdio: ["ignore", "inherit", "inherit"] });
}

function onPath(command: string): boolean {
  try {
    execFileSync(command, ["--version"], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

function wasmPack(): string {
  if (onPath("wasm-pack")) return "wasm-pack";
  const cacheHome = process.env.XDG_CACHE_HOME ?? path.join(homedir(), ".cache");
  const root = path.join(cacheHome, "nlp-stack-wasm", `wasm-pack-${WASM_PACK_VERSION}`);
  const binary = path.join(root, "bin", process.platform === "win32" ? "wasm-pack.exe" : "wasm-pack");
  if (!existsSync(binary)) {
    console.error(`wasm-pack not found on PATH; installing ${WASM_PACK_VERSION} into ${root}`);
    run("cargo", ["install", "wasm-pack", "--locked", "--version", WASM_PACK_VERSION, "--root", root], packageRoot);
  }
  return binary;
}

const work = mkdtempSync(path.join(tmpdir(), "nlp-stack-wasm-"));
try {
  const source = path.join(work, "nlp-stack");
  mkdirSync(source);
  run("git", ["init", "--quiet"], source);
  run("git", ["fetch", "--quiet", "--depth=1", repository, commit], source);
  run("git", ["checkout", "--quiet", "--detach", "FETCH_HEAD"], source);
  const fetched = execFileSync("git", ["rev-parse", "HEAD"], { cwd: source, encoding: "utf8" }).trim();
  if (fetched !== commit) throw new Error(`fetched ${fetched}, expected ${commit}`);

  // rustup installs the pinned toolchain on first use; the WASM target is added explicitly.
  if (onPath("rustup")) run("rustup", ["target", "add", "wasm32-unknown-unknown"], source);
  const wasmPackBinary = wasmPack();

  for (const { name, glue } of PACKAGES) {
    const out = path.join(work, "out", name);
    run(
      wasmPackBinary,
      ["build", path.join(source, "crates/bindings", name), "--release", "--target", "web", "--out-dir", out, "--out-name", glue, "--", "--locked"],
      source,
    );

    const target = path.join(packageRoot, name);
    const pkg = path.join(target, "pkg");
    rmSync(pkg, { recursive: true, force: true });
    mkdirSync(pkg, { recursive: true });
    copyFileSync(path.join(out, `${glue}.js`), path.join(pkg, `${glue}.js`));
    copyFileSync(path.join(out, `${glue}.d.ts`), path.join(pkg, `${glue}.d.ts`));
    const bytes = readFileSync(path.join(out, `${glue}_bg.wasm`)).toString("base64");
    writeFileSync(
      path.join(pkg, "wasm-bytes.js"),
      `// Generated by scripts/build.ts from nlp-stack ${commit}.\n` +
        `const base64 = "${bytes}";\n` +
        "export default Uint8Array.from(atob(base64), (char) => char.charCodeAt(0));\n",
    );
    copyFileSync(path.join(source, "packages", name, "index.d.ts"), path.join(target, "index.d.ts"));
    writeFileSync(path.join(pkg, "SOURCE"), `${repository}#${commit}\n`);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
